const { chromium } = require('playwright');
const ok = (c, m) => { console.log((c ? 'OK  ' : 'FALHA ') + m); if (!c) process.exitCode = 1; };
const U = 'http://localhost:8000';
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
  p.on('dialog', d => d.accept());
  await p.goto(U + '/#/orcamentos'); await p.waitForSelector('#form-novo');
  await p.fill('[name=nome]', 'Reforma da Escola Estadual Rio Branco'); await p.fill('[name=cliente]', 'Secretaria de Educação');
  await p.fill('[name=local]', 'Aracaju/SE'); await p.fill('[name=bdi]', '24,23');
  await p.click('#form-novo button'); await p.waitForSelector('.planilha');
  ok(/#\/orcamento\/\d+/.test(p.url()), 'Criou orçamento e abriu a planilha');
  const add = async (etapaIdx, termo, qtd) => {
    const inp = (await p.$$('.add-q'))[etapaIdx]; await inp.fill(termo);
    await p.waitForSelector('.add-res:not([hidden]) li[data-k]'); await p.keyboard.press('Enter');
    await p.waitForFunction(() => document.activeElement && document.activeElement.classList.contains('qtd'));
    await p.keyboard.type(qtd); await p.keyboard.press('Enter'); await p.waitForTimeout(350);
  };
  await add(0, 'limpeza manual terreno', '850');
  await add(0, 'placa de obra', '6');
  await p.fill('#nova-etapa', 'Alvenaria e revestimento'); await p.click('#form-etapa button'); await p.waitForTimeout(350);
  await add(1, '103335', '420');
  await add(1, 'chapisco', '840');
  await add(1, 'emboço massa unica', '840');
  await p.fill('#nova-etapa', 'Pintura'); await p.click('#form-etapa button'); await p.waitForTimeout(350);
  await add(2, 'pintura acrilica 02 demaos', '1260');
  const n = await p.$$eval('tr.item', r => r.length);
  ok(n === 6, `Seis itens na planilha (${n})`);
  const nums = await p.$$eval('tr.item .n', r => r.map(x => x.textContent));
  ok(JSON.stringify(nums) === JSON.stringify(['1.1', '1.2', '2.1', '2.2', '2.3', '3.1']), 'Numeração ' + nums.join(' '));
  const total1 = await p.textContent('.orc-totais .total b');
  await p.fill('#orc-bdi', '0'); await p.press('#orc-bdi', 'Tab'); await p.waitForTimeout(500);
  const custo = await p.textContent('.orc-totais div:first-child b'); const total0 = await p.textContent('.orc-totais .total b');
  ok(custo === total0 && total0 !== total1, `BDI 0% → total = custo direto (${total0}); com 24,23%: ${total1}`);
  await p.fill('#orc-bdi', '24,23'); await p.press('#orc-bdi', 'Tab'); await p.waitForTimeout(500);
  await p.screenshot({ path: 'final/orc_planilha.png', fullPage: true });
  await p.click('.abas-orc a[href$="abc-servicos"]'); await p.waitForSelector('.abc');
  await p.screenshot({ path: 'final/orc_abc_serv.png' });
  await p.click('.abas-orc a[href$="abc-insumos"]');
  await p.waitForFunction(() => document.querySelector('#orc-corpo .sub') && document.querySelector('#orc-corpo .sub').textContent.includes('desmontada') && document.querySelector('.abc'));
  const nIns = await p.$$eval('.abc tbody tr', r => r.length);
  ok(nIns > 20, `Curva ABC de insumos desmontou as composições (${nIns} insumos)`);
  await p.screenshot({ path: 'final/orc_abc_ins.png' });
  const [dl] = await Promise.all([p.waitForEvent('download'), p.click('a[href$="exportar.xlsx"]')]);
  await dl.saveAs('final/orcamento_exemplo.xlsx'); ok(true, 'Excel baixado: ' + dl.suggestedFilename());
  await p.goto(U + '/#/composicao/ORSE/00006'); await p.waitForSelector('[data-adicionar]');
  await p.click('[data-adicionar]'); await p.waitForSelector('#dlg-adicionar[open]');
  await p.fill('#dlg-qtd', '12,5'); await p.click('#dlg-ok'); await p.waitForFunction(() => document.querySelector('#aviso').textContent.includes('Adicionado'));
  ok((await p.textContent('#aviso')).includes('Adicionado a'), 'Adicionar pela consulta: ' + (await p.textContent('#aviso')).slice(0, 80));
  await p.click('#aviso a'); await p.waitForSelector('.planilha');
  ok((await p.$$eval('tr.item', r => r.length)) === 7, 'Item entrou na última etapa do orçamento');
  const m = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  await m.goto(p.url()); await m.waitForSelector('.planilha');
  await m.screenshot({ path: 'final/orc_mobile.png' });
  ok(await m.evaluate(() => document.documentElement.scrollWidth) <= 390, 'Celular sem rolagem lateral da página');
  ok(errs.length === 0, 'Sem erros de JavaScript ' + JSON.stringify(errs));
  await b.close();
})();
