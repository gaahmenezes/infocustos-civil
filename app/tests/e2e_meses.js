const { chromium } = require('playwright');

// data-base: o seletor abre um quadro com o mês de cada base; ORSE e SINAPI mudam juntas aqui
const mudarMes = async (p, m) => { await p.click('#dt-campo'); for (const b of ['ORSE', 'SINAPI']) await p.selectOption(`[data-dt-mes="${b}"]`, m); await p.click('[data-dt="aplicar"]'); await p.waitForTimeout(300); };
const ok = (c, m) => { console.log((c ? 'OK  ' : 'FALHA ') + m); if (!c) process.exitCode = 1; };
const U = process.argv[3] || 'http://localhost:8000/';
const R = (h) => {
  if (!U.includes('8100')) return U + h;
  const m = h.match(/^#\/(composicao|insumo)\/(ORSE|SINAPI)\/(\w+)$/);
  return U + (m ? '#' + (m[1] === 'composicao' ? 'c' : 'i') + '-' + m[2] + '-' + m[3] : h.replace('#/', '#'));
};
const OUT = process.argv[2] || require('os').tmpdir();  // capturas de tela: pasta indicada ou a temporária do sistema
const norm = (t) => t.replace(/\s+/g, ' ');
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && !m.text().includes('404') && errs.push(m.text()));
  await p.goto(U + '#/'); await p.waitForSelector('#dt-campo');
  ok((await p.textContent('#dt-campo')).includes('ORSEago/2026'), 'Abre em agosto/2026 (ORSE e SINAPI)');
  await p.fill('#q', '00003'); await p.waitForTimeout(500);
  ok(norm(await p.textContent('.res-preco')).startsWith('R$ 5,17'), 'Agosto mostra só o preço de agosto: ' + norm(await p.textContent('.res-preco')));
  ok((await p.$$('.var')).length === 0, 'Sem selos de variação na consulta');
  await p.click('.res'); await p.waitForSelector('.arvore');
  ok(!(await p.$('.historico')), 'Composição sem histórico de outros meses');
  await p.screenshot({ path: OUT + '/1_agosto.png' });
  await mudarMes(p, '2026-05'); await p.waitForFunction(() => document.querySelector('.preco-grande .valor') && document.querySelector('.preco-grande .valor').textContent.includes('4,90') && document.querySelector('.res-preco') && document.querySelector('.res-preco').textContent.includes('4,90'));
  ok(norm(await p.textContent('.res-preco')).startsWith('R$ 4,90'), 'Aba de maio: busca e composição com preços de maio');
  await p.screenshot({ path: OUT + '/2_maio.png' });
  await p.goto(R('#/composicao/SINAPI/103335')); await p.waitForFunction(() => document.querySelector('.ficha-cod .cb-num') && document.querySelector('.ficha-cod .cb-num').textContent === '103335');
  ok(norm(await p.textContent('.valor')).includes('139,37'), 'Em maio, 103335 abre normalmente');
  await mudarMes(p, '2026-08'); await p.waitForSelector('.erro');
  ok(norm(await p.textContent('.erro')).includes('não existe em agosto/2026'), 'Em agosto, 103335 avisa que não existe no mês');
  ok(!!(await p.$('.erro [data-mes="2026-05"]')), 'Oferece abrir em maio');
  await p.goto(R('#/encargos')); await p.waitForSelector('.enc');
  ok(norm(await p.textContent('.encargos')).includes('69,72%') && norm(await p.textContent('.encargos')).includes('111,51%'), 'Encargos de agosto');
  await p.screenshot({ path: OUT + '/3_encargos.png', fullPage: true });
  await mudarMes(p, '2026-05'); await p.waitForFunction(() => document.querySelector('.encargos .pag-cab').textContent.includes('maio'));
  ok(norm(await p.textContent('.encargos')).includes('ainda não foi carregado'), 'Maio: avisa que o detalhamento não foi carregado');
  await mudarMes(p, '2026-08');
  await p.click('.abas a[data-aba="comparativo"]'); await p.waitForSelector('.comparativo table');
  ok(norm(await p.textContent('.blocos')).includes('Só em agosto/2026'), 'Aba Comparativo entre meses');
  await p.fill('#cmp-q', 'chapisco'); await p.waitForFunction(() => [...document.querySelectorAll('.comparativo tbody tr')].length && [...document.querySelectorAll('.comparativo tbody .desc')].every((t) => /hapisco/.test(t.textContent)));
  ok(true, 'Filtro do comparativo: ' + (await p.$$('.comparativo tbody tr')).length + ' itens com chapisco');
  await p.click('.comparativo [data-hist]'); await p.waitForSelector('.cmp-detalhe .historico');
  ok(norm(await p.textContent('.cmp-detalhe')).includes('maio/2026'), 'Preço do item mês a mês no comparativo');
  await p.screenshot({ path: OUT + '/4_comparativo.png' });
  await p.goto(R('#/orcamentos')); await p.click('#novo-orc'); await p.waitForSelector('#dlg-novo-orc[open]');
  await p.fill('[name=nome]', 'Reforma de escola'); await p.selectOption('[name=referencia]', '2026-05'); await p.fill('[name=bdi]', '24,23');
  await p.click('#form-novo [type=submit]'); await p.waitForSelector('.planilha');
  const add = async (termo, qtd) => {
    const inp = (await p.$$('.add-q'))[0]; await inp.fill(termo);
    await p.waitForSelector('.add-res:not([hidden]) li[data-k]'); await p.keyboard.press('Enter');
    await p.waitForFunction(() => document.activeElement && document.activeElement.classList.contains('qtd'));
    await p.keyboard.type(qtd); await p.keyboard.press('Enter'); await p.waitForTimeout(350);
  };
  await add('00003', '850'); await add('103335', '420');
  ok(norm(await p.textContent('.planilha')).includes('139,37'), 'Orçamento de maio usa preços de maio');
  ok((await p.$$('.ref-item')).length === 0 && !(await p.$('.desatualizado')), 'Sem avisos de comparação no orçamento');
  await p.click('#orc-editar'); await p.selectOption('#orc-mes', '2026-08'); await p.waitForSelector('#orc-mes-ok');
  ok(norm(await p.textContent('#orc-mudar-mes')).includes('103335'), 'Trocar data-base avisa o item que não existe em agosto');
  await p.screenshot({ path: OUT + '/5_mudar_mes.png' });
  await p.click('#orc-mes-ok'); await p.waitForFunction(() => document.querySelector('#aviso').textContent.includes('Data-base alterada'));
  await p.waitForSelector('.planilha');
  ok(norm(await p.textContent('.planilha')).includes('5,17'), 'Depois de mudar: preços de agosto');
  ok((await p.$$('.ref-item')).length === 1, 'Item sem preço em agosto fica identificado');
  const r = await p.$$eval('.add-q', (x) => x[0].placeholder);
  ok(r.includes('agosto/2026'), 'Busca da etapa usa o mês do orçamento');
  const m = await ctx.newPage(); await m.setViewportSize({ width: 390, height: 844 });
  await m.goto(R('#/comparativo')); await m.waitForSelector('.comparativo table');
  ok(await m.evaluate(() => document.documentElement.scrollWidth) <= 390, 'Celular sem rolagem lateral (comparativo)');
  await m.goto(U + '#/'); await m.waitForSelector('#dt-campo');
  ok(await m.evaluate(() => document.documentElement.scrollWidth) <= 390, 'Celular sem rolagem lateral (consulta)');
  await m.screenshot({ path: OUT + '/6_celular.png' });
  await p.goto(U + '#/'); await p.waitForSelector('#dt-campo'); await p.click('#dt-campo'); const ops = await p.$$eval('[data-dt-mes="ORSE"] option', (o) => o.map((x) => x.textContent)); await p.keyboard.press('Escape');
  ok(ops[0].startsWith('agosto/2026') && ops[0].includes('mais recente') && ops[1] === 'maio/2026', 'Lista de meses: ' + ops.join(' | '));
  ok(errs.length === 0, 'Sem erros de JavaScript ' + JSON.stringify(errs));
  await b.close();
})();
