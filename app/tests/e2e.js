const { chromium } = require('playwright');
const ok = (c, m) => { console.log((c ? 'OK  ' : 'FALHA ') + m); if (!c) process.exitCode = 1; };
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1366, height: 860 } });
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
  await p.goto('http://localhost:8000/'); await p.waitForSelector('.res');
  await p.fill('#q', 'concreto fck 25'); await p.waitForTimeout(500);
  await p.press('#q', 'Enter'); await p.waitForSelector('.ficha h2');
  ok(/#\/(composicao|insumo)\//.test(p.url()), 'Enter na busca abre o primeiro resultado: ' + p.url().split('#')[1]);
  await p.goto('http://localhost:8000/#/composicao/ORSE/00005'); await p.waitForSelector('.secao-bt');
  await p.focus('.res'); await p.keyboard.press('ArrowDown');
  ok(await p.evaluate(() => document.activeElement.closest('li') === document.querySelectorAll('.res')[1].closest('li')), 'Seta para baixo navega na lista');
  const sec = await p.$('.secao-bt'); await sec.click();
  ok(await p.evaluate(() => [...document.querySelector('tbody[data-secao]').querySelectorAll('tr:not(.secao)')].every(t => t.hidden)), 'Seção recolhe');
  await sec.click();
  await p.goto('http://localhost:8000/#/composicao/ORSE/00004'); await p.waitForSelector('.expandir');
  const n0 = await p.$$eval('tr', t => t.length); await p.click('.expandir'); await p.waitForTimeout(400);
  const n1 = await p.$$eval('tr', t => t.length); await p.click('.expandir'); await p.waitForTimeout(200);
  const n2 = await p.$$eval('tr', t => t.length);
  ok(n1 > n0 && n2 === n0, `Serviço auxiliar abre e fecha (${n0} → ${n1} → ${n2})`);
  await p.click('a[href^="#/insumo/"]'); await p.waitForFunction(() => document.querySelector('.selo') && document.querySelector('.selo').textContent === 'Insumo', null, { timeout: 5000 }).catch(() => {});
  ok((await p.textContent('.selo')) === 'Insumo', 'Clique no insumo abre a ficha do insumo');
  await p.goBack(); await p.waitForSelector('.expandir');
  ok(/00004/.test(p.url()), 'Voltar do navegador retorna à composição');
  await p.goto('http://localhost:8000/#/composicao/ORSE/abc'); await p.waitForSelector('.erro');
  ok(true, 'Código inexistente mostra mensagem de erro: ' + (await p.textContent('.erro')).slice(0, 60));
  await p.click('[data-filtro="base"] [data-v="SINAPI"]'); await p.fill('#q', 'tijolo'); await p.waitForTimeout(500);
  ok(await p.$$eval('.res-cod', e => e.every(x => x.textContent.includes('/SINAPI'))), 'Filtro SINAPI aplicado');
  await p.fill('#q', 'xyzwq'); await p.waitForTimeout(500);
  ok((await p.textContent('#contagem')).startsWith('Nada encontrado'), 'Busca sem resultado orienta o usuário');
  const d = await b.newPage({ viewport: { width: 1366, height: 860 }, colorScheme: 'dark', deviceScaleFactor: 1 });
  await d.goto('http://localhost:8000/#/composicao/SINAPI/103335'); await d.waitForSelector('.barra');
  await d.screenshot({ path: 'final/escuro.png' });
  const reais = errs.filter(e => !e.includes('404')); ok(reais.length === 0, 'Sem erros de JavaScript (o 404 do código inexistente é esperado) ' + JSON.stringify(reais));
  await b.close();
})();
