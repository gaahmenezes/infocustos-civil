const { chromium } = require('playwright');
const ok = (c, m) => { console.log((c ? 'OK  ' : 'FALHA ') + m); if (!c) process.exitCode = 1; };
const U = 'http://localhost:8100/index.html';
(async () => {
  const b = await chromium.launch();
  const ctx = await b.newContext({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 1 });
  await ctx.grantPermissions(['clipboard-read', 'clipboard-write'], { origin: 'http://localhost:8100' });
  const p = await ctx.newPage();
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
  const t0 = Date.now(); await p.goto(U); await p.waitForSelector('.res'); ok(true, `Base carregada em ${Date.now() - t0} ms`);
  await p.fill('#q', 'chapisco'); await p.waitForTimeout(400);
  ok((await p.textContent('.res-desc')).startsWith('Chapisco'), 'Busca local: ' + (await p.textContent('.res-desc')).slice(0, 50));
  await p.fill('#q', '3'); await p.waitForTimeout(400);
  ok((await p.textContent('.res-cod .cb')) === '00003ORSE', 'Busca por código "3"');
  await p.click('.res'); await p.waitForSelector('.arvore');
  ok(p.url().endsWith('#c-ORSE-00003') && (await p.textContent('.valor')).includes('4,90'), 'Composição 00003 abre com R$ 4,90');
  await p.goto(U + '#c-ORSE-00004'); await p.waitForSelector('.expandir'); await p.click('.expandir'); await p.waitForTimeout(300);
  ok((await p.$$('tr.filho')).length > 5, 'Serviço auxiliar abre');
  await p.click('[data-copiar]'); await p.waitForTimeout(200);
  const clip = await p.evaluate(() => navigator.clipboard.readText());
  ok(clip.includes('02451') && clip.includes('\t'), 'Copiar para o Excel: ' + clip.split('\n').length + ' linhas');
  await p.goto(U + '#i-SINAPI-06111'); await p.waitForSelector('.uso');
  ok((await p.textContent('.fatos')).includes('11.010'), 'Insumo mostra usado em 11.010 composições');
  await p.click('.abas a[data-aba="orcamentos"]'); await p.waitForSelector('.lista-orc');
  ok((await p.textContent('.lista-orc')).includes('Exemplo'), 'Orçamento de exemplo criado');
  await p.click('.lista-orc a'); await p.waitForSelector('.planilha');
  const tot = await p.textContent('.orc-totais .total b');
  ok(tot === 'R$ 183.255,06', 'Total do exemplo igual ao do servidor: ' + tot);
  const inp = (await p.$$('.add-q'))[2]; await inp.fill('textura acrilica'); await p.waitForSelector('.add-res:not([hidden]) li[data-k]');
  await p.keyboard.press('Enter'); await p.waitForFunction(() => document.activeElement.classList.contains('qtd'));
  await p.keyboard.type('300'); await p.keyboard.press('Enter'); await p.waitForTimeout(300);
  ok((await p.$$('tr.item')).length === 7, 'Item adicionado pela busca da etapa');
  await p.click('#orc-editar'); await p.fill('#orc-bdi', '0'); await p.press('#orc-bdi', 'Tab'); await p.waitForTimeout(300);
  ok((await p.textContent('.orc-totais div:first-child b')) === (await p.textContent('.orc-totais .total b')), 'BDI 0% recalcula');
  await p.fill('#orc-bdi', '24,23'); await p.press('#orc-bdi', 'Tab'); await p.waitForTimeout(300);
  await p.click('.abas-orc a[href$="abc-insumos"]');
  await p.waitForFunction(() => document.querySelector('.abc') && document.querySelector('#orc-corpo .sub').textContent.includes('desmontada'));
  ok((await p.$$('.abc tbody tr')).length > 50, 'Curva ABC de insumos: ' + (await p.$$('.abc tbody tr')).length + ' insumos');
  await p.reload(); await p.waitForSelector('.abc');
  ok((await p.$$('.abc tbody tr')).length > 50, 'Orçamento continua salvo depois de recarregar');
  await p.goto(U + '#orcamentos'); await p.click('#novo-orc'); await p.waitForSelector('#dlg-novo-orc[open]');
  await p.fill('[name=nome]', 'Teste'); await p.click('#form-novo [type=submit]'); await p.waitForSelector('.planilha');
  await p.click('.orc-barra .menu summary'); await p.click('#orc-excluir'); await p.waitForSelector('.lista-orc');
  ok(!(await p.textContent('.lista-orc')).includes('Teste\n'), 'Orçamento excluído');
  await p.goto(U + '#c-SINAPI-103335'); await p.waitForSelector('[data-adicionar]'); await p.click('[data-adicionar]');
  await p.waitForSelector('#dlg-adicionar[open]'); await p.fill('#dlg-qtd', '12,5'); await p.click('#dlg-ok');
  await p.waitForFunction(() => document.querySelector('#aviso').textContent.includes('Adicionado'));
  ok(true, 'Adicionar ao orçamento pela consulta');
  await p.screenshot({ path: 'final/art_comp.png' });
  const m = await ctx.newPage(); await m.setViewportSize({ width: 390, height: 844 });
  await m.goto(U + '#orcamentos'); await m.waitForSelector('.lista-orc');
  ok(await m.evaluate(() => document.documentElement.scrollWidth) <= 390, 'Celular sem rolagem lateral');
  const d = await b.newPage({ viewport: { width: 1280, height: 800 }, colorScheme: 'dark' });
  await d.goto(U + '#c-SINAPI-103335'); await d.waitForSelector('.barra'); await d.screenshot({ path: 'final/art_dark.png' });
  ok(errs.length === 0, 'Sem erros de JavaScript ' + JSON.stringify(errs));
  await b.close();
})();
