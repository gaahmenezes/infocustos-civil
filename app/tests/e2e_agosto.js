const { chromium } = require('playwright');
const ok = (c, m) => { console.log((c ? 'OK  ' : 'FALHA ') + m); if (!c) process.exitCode = 1; };
const U = 'http://localhost:8000/';
const OUT = process.argv[2];
(async () => {
  const b = await chromium.launch();
  const p = await b.newPage({ viewport: { width: 1440, height: 900 }, deviceScaleFactor: 2 });
  const errs = []; p.on('pageerror', e => errs.push(e.message)); p.on('console', m => m.type() === 'error' && errs.push(m.text()));
  await p.goto(U); await p.waitForSelector('.res');
  ok((await p.textContent('#referencia')).includes('agosto/2026'), 'Cabeçalho: ' + (await p.textContent('#referencia')).replace(/\s+/g, ' '));
  await p.fill('#q', 'alvenaria bloco ceramico 14'); await p.waitForTimeout(500);
  ok((await p.$$('.res .var')).length > 3, 'Busca mostra selos de variação');
  await p.screenshot({ path: OUT + '/1_busca.png' });
  await p.goto(U + '#/composicao/ORSE/00003'); await p.waitForSelector('.historico');
  ok((await p.textContent('.historico')).includes('maio/2026') && (await p.textContent('.historico')).includes('5,17'), 'Histórico na composição');
  await p.screenshot({ path: OUT + '/2_composicao.png' });
  await p.goto(U + '#/composicao/SINAPI/103335'); await p.waitForSelector('.aviso-ref');
  ok(true, 'Aviso de item fora da base: ' + (await p.textContent('.aviso-ref')).slice(0, 70));
  await p.goto(U + '#/insumo/SINAPI/00370'); await p.waitForSelector('.historico');
  await p.screenshot({ path: OUT + '/3_insumo.png' });
  await p.click('.abas a[data-aba="variacao"]'); await p.waitForSelector('.variacao table');
  ok((await p.$$('.variacao tbody tr')).length > 50, 'Página O que mudou');
  await p.screenshot({ path: OUT + '/4_variacao.png' });
  await p.click('[data-var="tipo"] [data-v="insumo"]'); await p.waitForFunction(() => document.querySelector('.variacao .sub').textContent.includes('insumos'));
  ok(true, 'Filtro de insumos na variação');
  await p.goto(U + '#/orcamentos'); await p.waitForSelector('.lista-orc');
  ok((await p.textContent('.lista-orc')).includes('desatualizado'), 'Lista marca orçamento desatualizado');
  await p.click('.lista-orc a'); await p.waitForSelector('#orc-desatualizado');
  ok((await p.$$('.ref-item')).length === 6, 'Itens marcados com a data-base antiga');
  await p.click('#orc-ver-impacto'); await p.waitForSelector('#orc-atualizar');
  const imp = (await p.textContent('.totais-imp')).replace(/\s+/g, ' ');
  ok(imp.includes('203.045,94'), 'Impacto: ' + imp);
  await p.screenshot({ path: OUT + '/5_orcamento_impacto.png', fullPage: true });
  await p.click('#orc-duplicar-atualizar'); await p.waitForFunction(() => location.hash.includes('/orcamento/2'));
  await p.waitForSelector('.planilha');
  const tot = await p.textContent('.orc-totais .total b');
  ok(tot.replace(/\s/g, ' ').includes('203.045,94'), 'Cópia atualizada: ' + tot);
  ok((await p.$$('.ref-item')).length === 1, 'Na cópia, só o item que saiu da base continua em maio');
  ok(!!(await p.$('#orc-desatualizado')), 'Cópia ainda avisa do item com preço antigo');
  await p.screenshot({ path: OUT + '/6_orcamento_atualizado.png' });
  await p.goto(U + '#/orcamentos'); await p.waitForSelector('.lista-orc');
  ok((await p.$$('.lista-orc tbody tr')).length === 2, 'Original preservado e cópia criada');
  const m = await b.newPage({ viewport: { width: 390, height: 844 }, deviceScaleFactor: 2 });
  await m.goto(U + '#/variacao'); await m.waitForSelector('.variacao table');
  ok(await m.evaluate(() => document.documentElement.scrollWidth) <= 390, 'Celular sem rolagem lateral');
  ok(errs.length === 0, 'Sem erros de JavaScript ' + JSON.stringify(errs));
  await b.close();
})();
